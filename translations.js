// Current active language
let currentLang = localStorage.getItem('renzifarm_lang') || 'id';

function applyLanguage(lang) {
    if (!renzifarmI18n[lang]) lang = 'id';
    currentLang = lang;
    localStorage.setItem('renzifarm_lang', lang);

    document.documentElement.lang = lang;

    const dict = renzifarmI18n[lang];

    // Update text content of data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            el.innerHTML = dict[key];
        }
    });

    // Update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) {
            el.setAttribute('placeholder', dict[key]);
        }
    });

    // Update Language Dropdown Button Display
    const langBtnText = document.getElementById('currentLangLabel');
    if (langBtnText) {
        if (lang === 'id') langBtnText.innerHTML = '🇮🇩 ID';
        else if (lang === 'en') langBtnText.innerHTML = '🇬🇧 EN';
        else if (lang === 'ja') langBtnText.innerHTML = '🇯🇵 JA';
    }

    // Notify listeners (e.g. script.js for dynamic currency or AI copilot responses)
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: lang } }));
}

// Inisialisasi saat script dimuat
document.addEventListener('DOMContentLoaded', () => {
    applyLanguage(currentLang);

    // Setup listener on language selector items
    document.querySelectorAll('.lang-select-item').forEach(item => {
        item.addEventListener('click', function (e) {
            e.preventDefault();
            const selected = this.getAttribute('data-lang');
            applyLanguage(selected);
        });
    });
});

